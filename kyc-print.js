/* Professional KYC documents in the same layout as the Leave form (logo, navy and gold, one shared preview
   with Print, Save as PDF and Download).
   VIRTUOSO_KYCPRINT.submission(sub)  = a completed KYC submission with the review decision
   VIRTUOSO_KYCPRINT.blank(form)      = a blank, print-ready copy of a form (from Client KYC or the Form builder) */
(function(){
  const esc=s=>String(s==null?'':s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const CSS=`@page{size:A4;margin:12mm 14mm}*{box-sizing:border-box}
body{margin:0;background:#e9ecf3;font:13px/1.5 "Segoe UI",Arial,Helvetica,sans-serif;color:#14213d;-webkit-print-color-adjust:exact;print-color-adjust:exact}
.page{width:210mm;min-height:297mm;margin:0 auto;background:#fff;padding:14mm 16mm}
@media print{body{background:#fff}.page{width:auto;min-height:0;margin:0;padding:0}}
.hd{display:flex;align-items:center;gap:16px;border-bottom:3px solid #c9a227;padding-bottom:12px}
.hd img{height:64px;width:auto;display:block}.hd .co{flex:1}.hd .co b{display:block;font-size:17px;color:#0f1f4d}.hd .co span{color:#5b6684;font-size:12px}
.hd .meta{text-align:right;font-size:12px;color:#5b6684}.hd .meta b{color:#0f1f4d}
h1{margin:16px 0 2px;font-size:20px;letter-spacing:1.2px;text-transform:uppercase;color:#0f1f4d;text-align:center}
.sub{text-align:center;color:#5b6684;font-size:12px;margin-bottom:10px}
h2{margin:14px 0 5px;font-size:12px;letter-spacing:1.2px;text-transform:uppercase;color:#fff;background:#0f1f4d;padding:5px 10px;border-left:5px solid #c9a227;break-after:avoid}
p.pa{margin:6px 0;color:#33406b;font-size:12px}
table.f{width:100%;border-collapse:collapse}
table.f td{border:1px solid #c8cfe0;padding:6px 10px;vertical-align:top}
table.f td.k{width:34%;background:#f3f5fa;color:#33406b;font-weight:600}
table.f tr{break-inside:avoid}
.na{color:#8a93ad;font-style:italic}
.sigimg{max-height:80px;max-width:100%;display:block;border-bottom:1px solid #14213d}
.docimg{max-width:100%;max-height:220px;display:block;margin-top:6px;border:1px solid #c8cfe0}
.stamp{display:inline-block;border:2px solid #0f1f4d;color:#0f1f4d;padding:2px 10px;border-radius:4px;font-weight:700;letter-spacing:1px;text-transform:uppercase;font-size:11px}
.stamp.ok{border-color:#1e7a45;color:#1e7a45}.stamp.bad{border-color:#b3261e;color:#b3261e}
.sig{display:grid;grid-template-columns:1fr 1fr;gap:26px;margin-top:26px}.sig div{border-top:1px solid #14213d;padding-top:4px;font-size:12px;color:#33406b}
.q{margin:0 0 10px;break-inside:avoid}.q .l{font-weight:600;color:#0f1f4d}.q .h{font-size:11.5px;color:#6a7592}
.line{border-bottom:1px solid #7b86a6;height:24px}.box{border:1px solid #7b86a6;height:80px}.o{margin:3px 0}.sbx{border-bottom:1px solid #7b86a6;height:56px;width:260px}
.bx{display:inline-block;width:13px;height:13px;border:1.5px solid #0f1f4d;vertical-align:-2px;margin-right:6px}
.ft{margin-top:18px;border-top:1px solid #c8cfe0;padding-top:8px;font-size:11px;color:#6a7592;display:flex;justify-content:space-between}`;
  const head=(img,ref,lines)=>`<div class="hd"><img src="${esc(img)}" alt="Virtuoso System logo"><div class="co"><b>Virtuous Accounting Solutions CC</b><span>Virtuoso System &middot; Windhoek, Namibia</span></div><div class="meta">${ref?`Reference: <b>${esc(ref)}</b><br>`:''}${lines.join('<br>')}</div></div>`;
  const wrap=(title,inner)=>`<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${esc(title)}</title><meta name="viewport" content="width=device-width,initial-scale=1"><style>${CSS}</style></head><body><div class="page">${inner}<div class="ft"><span>Virtuous Accounting Solutions CC &middot; Confidential client record</span><span>Generated by Virtuoso System</span></div></div></body></html>`;
  const today=()=>new Date().toLocaleDateString('en-GB',{day:'numeric',month:'long',year:'numeric'});
  const visible=(f,form,ans)=>typeof kVis==='function'?kVis(f,form,ans):true;
  const empty=v=>v==null||v===''||(Array.isArray(v)&&!v.length);

  function submissionHTML(s,form,img){
    const ans=s.ans||{};
    const cls={Approved:'ok',Rejected:'bad'}[s.status]||'';
    let name='';try{name=typeof kNameOf==='function'?kNameOf(s):''}catch(e){}
    let body='',open=false;
    const startTable=()=>{if(!open){body+='<table class="f"><tbody>';open=true}};
    const endTable=()=>{if(open){body+='</tbody></table>';open=false}};
    form.fields.forEach(f=>{
      if(f.type==='head'){endTable();body+=`<h2>${esc(f.label)}</h2>`;return}
      if(f.type==='para'){endTable();body+=`<p class="pa">${esc(f.label)}</p>`;return}
      if(!visible(f,form,ans))return;
      const v=ans[f.id];let out;
      if(f.type==='sign')out=v?`<img class="sigimg" src="${esc(v)}" alt="Signature">`:'<span class="na">Not signed</span>';
      else if(f.type==='file')out=v&&v.name?`${esc(v.name)}${/^data:image/.test(v.url||'')?`<img class="docimg" src="${esc(v.url)}" alt="${esc(v.name)}">`:''}`:'<span class="na">Not provided</span>';
      else if(empty(v))out='<span class="na">Not provided</span>';
      else out=esc(Array.isArray(v)?v.join('; '):v).replace(/\n/g,'<br>');
      startTable();body+=`<tr><td class="k">${esc(f.label)}</td><td>${out}</td></tr>`;
    });
    endTable();
    const notes=(s.notes||[]).map(n=>`<tr><td class="k">${esc(n.by)}<br><span style="font-weight:400">${esc(n.at)}</span></td><td>${esc(n.text).replace(/\n/g,'<br>')}</td></tr>`).join('');
    const review=`<h2>Review decision</h2><table class="f"><tbody>
      <tr><td class="k">Decision</td><td><span class="stamp ${cls}">${esc(s.status||'Pending')}</span>${s.reviewedAt?` &nbsp; on ${esc(s.reviewedAt)}`:''}</td></tr>
      ${s.flag?`<tr><td class="k">Note to client</td><td>${esc(s.flag)}</td></tr>`:''}
      ${notes}</tbody></table>
      ${s.signed&&s.sigUrl?`<div style="margin-top:14px"><img class="sigimg" style="max-width:260px" src="${esc(s.sigUrl)}" alt="Reviewer signature"><div style="font-size:12px;color:#33406b;margin-top:3px">Authorised signature</div></div>`
        :'<div class="sig"><div>Authorised signature</div><div>Date</div></div>'}`;
    return wrap('KYC '+(s.ref||''),`${head(img,s.ref,['Status: <b>'+esc(s.status||'Pending')+'</b>','Received: '+esc(s.date||''),'Printed: '+today()])}
      <h1>${esc(form.title)}</h1><div class="sub">${esc(form.desc||'Client onboarding (KYC)')}${name?' &middot; '+esc(name):''}</div>${body}${review}`);
  }

  function blankHTML(form,img){
    let body='';
    form.fields.forEach(x=>{
      if(x.type==='head'){body+=`<h2>${esc(x.label)}</h2>`;return}
      if(x.type==='para'){body+=`<p class="pa">${esc(x.label)}</p>`;return}
      let c='<div class="line"></div>';
      if(x.type==='long')c='<div class="box"></div>';
      else if(['radio','select','check','yesno'].includes(x.type))c=(x.type==='yesno'?['Yes','No']:x.opts||[]).map(o=>`<div class="o"><span class="bx"></span>${esc(o)}</div>`).join('');
      else if(x.type==='file')c=`<div class="o"><span class="bx"></span>Copy attached: ${esc(x.label)}</div>`;
      else if(x.type==='sign')c='<div class="sbx"></div>';
      else if(x.type==='date')c='<div class="line"><span class="h">DD / MM / YYYY</span></div>';
      body+=`<div class="q"><div class="l">${esc(x.label)}${x.req?' <span style="color:#b3261e">*</span>':''}</div>${x.help?`<div class="h">${esc(x.help)}</div>`:''}${c}</div>`;
    });
    return wrap(form.title,`${head(img,'',['Blank form','Printed: '+today()])}
      <h1>${esc(form.title)}</h1><div class="sub">${esc(form.desc||'Please complete in block letters and sign where indicated.')}</div>${body}
      <div class="sig"><div>Signature</div><div>Date</div></div>`);
  }

  async function submission(s){
    const D=window.VIRTUOSO_DOCS;if(!D||!s)return;
    const form=typeof kForm==='function'?kForm(s.formId):null;if(!form)return;
    return D.overlay(submissionHTML(s,form,await D.logoData()),{title:'KYC document',name:'KYC-'+(s.ref||'document')});
  }
  async function blank(form){
    const D=window.VIRTUOSO_DOCS;if(!D||!form)return;
    return D.overlay(blankHTML(form,await D.logoData()),{title:(form.title||'Form')+' (blank copy)',name:(form.title||'form')+'-blank'});
  }
  window.VIRTUOSO_KYCPRINT={submission,blank,submissionHTML,blankHTML};
})();
